# --------------------------------------------------------------------------- #
# signal building blocks
# --------------------------------------------------------------------------- #
def _pink_noise(n: int, exponent: float, rng: np.random.Generator, sfreq: float) -> np.ndarray:
    """1/f^exponent noise via spectral shaping (unit standard deviation)."""
    white = rng.standard_normal(n)
    spectrum = np.fft.rfft(white)
    freqs = np.fft.rfftfreq(n, d=1.0 / sfreq)
    scaling = np.ones_like(freqs)
    positive = freqs > 0
    scaling[positive] = freqs[positive] ** (-exponent / 2.0)
    shaped = np.fft.irfft(spectrum * scaling, n=n)
    std = np.std(shaped)
    return shaped / std if std > 0 else shaped


def _band_noise(n: int, sfreq: float, band: tuple[float, float], rng: np.random.Generator) -> np.ndarray:
    """Band-limited noise, unit standard deviation, zero-phase filtered."""
    white = rng.standard_normal(n)
    low, high = band
    nyquist = sfreq / 2.0
    low = max(low, 1e-3)
    high = min(high, nyquist * 0.98)
    if high <= low:
        return np.zeros(n)
    sos = sps.butter(4, [low / nyquist, high / nyquist], btype="bandpass", output="sos")
    filtered = sps.sosfiltfilt(sos, white)
    std = np.std(filtered)
    return filtered / std if std > 0 else filtered


def _spindle_burst(sfreq: float, rng: np.random.Generator) -> np.ndarray:
    """A ~0.5-1.5 s waxing-waning 11-16 Hz burst (spindle surrogate)."""
    duration = float(rng.uniform(0.7, 1.4))
    n = int(duration * sfreq)
    t = np.arange(n) / sfreq
    frequency = float(rng.uniform(12.0, 15.0))
    phase = float(rng.uniform(0, 2 * np.pi))
    sigma = duration / 5.0
    envelope = np.exp(-0.5 * ((t - duration / 2.0) / sigma) ** 2)
    amplitude = float(rng.uniform(12.0, 28.0)) * UV
    return amplitude * np.sin(2 * np.pi * frequency * t + phase) * envelope


def _k_complex_wave(sfreq: float, rng: np.random.Generator) -> np.ndarray:
    """Biphasic slow deflection (negative peak followed by positive rebound)."""
    duration = float(rng.uniform(0.8, 1.6))
    n = int(duration * sfreq)
    t = np.arange(n) / sfreq
    t0 = 0.30 * duration
    neg = -float(rng.uniform(55.0, 95.0)) * UV
    pos = -0.45 * neg
    wave = neg * np.exp(-0.5 * ((t - t0) / (0.16 * duration)) ** 2)
    wave += pos * np.exp(-0.5 * ((t - (t0 + 0.42 * duration)) / (0.22 * duration)) ** 2)
    return wave


def _slow_wave(sfreq: float, rng: np.random.Generator) -> np.ndarray:
    """Single slow wave (0.5-2 Hz) with a smooth envelope."""
    duration = float(rng.uniform(0.6, 1.3))
    n = int(duration * sfreq)
    t = np.arange(n) / sfreq
    frequency = float(rng.uniform(0.6, 1.6))
    amplitude = float(rng.uniform(45.0, 105.0)) * UV
    envelope = np.hanning(n)
    return amplitude * np.sin(2 * np.pi * frequency * t) * envelope


def _add_events(
    epoch: np.ndarray,
    sfreq: float,
    profile: StageProfile,
    rng: np.random.Generator,
    effect_strength: float,
) -> dict[str, int]:
    """Insert stage-appropriate events; return ground-truth event counts."""
    n = epoch.size
    epoch_minutes = n / sfreq / 60.0
    counts = {"spindle": 0, "kcomplex": 0, "slow_wave": 0}

    def _place(wave: np.ndarray, label: str, max_attempts: int = 12) -> None:
        if wave.size >= n:
            return
        start = int(rng.integers(0, n - wave.size))
        epoch[start : start + wave.size] += wave
        counts[label] += 1
        _ = max_attempts

    for _ in range(int(rng.poisson(profile.spindle_per_min * epoch_minutes * effect_strength))):
        _place(_spindle_burst(sfreq, rng), "spindle")
    for _ in range(int(rng.poisson(profile.kcomplex_per_min * epoch_minutes * effect_strength))):
        _place(_k_complex_wave(sfreq, rng), "kcomplex")
    for _ in range(int(rng.poisson(profile.slow_wave_per_min * epoch_minutes * effect_strength))):
        _place(_slow_wave(sfreq, rng), "slow_wave")
    return counts


# --------------------------------------------------------------------------- #
# stage sequence and epochs
# --------------------------------------------------------------------------- #
def generate_stage_sequence(
    n_epochs: int, rng: np.random.Generator, start: str = "W", n3_allowed: bool = True
) -> list[str]:
    """Sample a plausible sleep-stage sequence from :data:`TRANSITION_MATRIX`."""
    stages = list(CANONICAL_STAGES)
    sequence = [start]
    current = start
    for _ in range(n_epochs - 1):
        probabilities = np.array(
            [TRANSITION_MATRIX[current].get(stage, 0.0) for stage in stages], dtype=float
        )
        if not n3_allowed:
            probabilities[stages.index("N3")] = 0.0
        probabilities = probabilities / probabilities.sum()
        current = stages[int(rng.choice(len(stages), p=probabilities))]
        sequence.append(current)
    return sequence


def generate_epoch(
    stage: str,
    sfreq: float,
    epoch_seconds: float,
    rng: np.random.Generator,
    effect_strength: float = 1.0,
    subject_scale: float = 1.0,
    subject_gain: dict[str, float] | None = None,
    add_artifact: bool = True,
) -> tuple[np.ndarray, dict[str, int]]:
    """Generate one synthetic EEG epoch for ``stage`` (volts)."""
    profile = STAGE_PROFILES[stage]
    n = int(round(epoch_seconds * sfreq))
    gains = dict(subject_gain or {})

    def _gain(band: str, value: float) -> float:
        """Blend the nominal stage gain with a subject-specific deviation."""
        deviation = gains.get(band, 0.0)
        scaled = value * (1.0 + deviation)
        return 1.0 + effect_strength * (scaled - 1.0)

    pink_exponent = profile.pink_exponent + gains.get("pink", 0.0)
    background = _pink_noise(n, pink_exponent, rng, sfreq)
    epoch = profile.broadband_gain * subject_scale * background * 14.0 * UV

    band_amplitudes_uv = {
        "delta": 6.0 * _gain("delta", profile.delta),
        "theta": 5.0 * _gain("theta", profile.theta),
        "alpha": 5.0 * _gain("alpha", profile.alpha),
        "sigma": 3.0 * _gain("sigma", profile.sigma),
        "beta": 2.5 * _gain("beta", profile.beta),
        "gamma": 1.5 * _gain("beta_high", profile.beta_high),
    }
    for band_name, amplitude_uv in band_amplitudes_uv.items():
        band = {"delta": (0.5, 4.0), "theta": (4.0, 8.0), "alpha": (8.0, 12.0),
                "sigma": (12.0, 16.0), "beta": (16.0, 30.0), "gamma": (30.0, 45.0)}[band_name]
        epoch += amplitude_uv * UV * subject_scale * _band_noise(n, sfreq, band, rng)

    counts = _add_events(epoch, sfreq, profile, rng, effect_strength)

    artifact_kind: str | None = None
    if add_artifact and rng.random() < profile.artifact_probability:
        kind = rng.choice(["transient", "flat", "drift"])
        artifact_kind = str(kind)
        if kind == "transient":
            start = int(rng.integers(0, max(1, n - int(0.2 * sfreq))))
            width = int(0.05 * sfreq)
            epoch[start : start + width] += 350.0 * UV * rng.choice([-1.0, 1.0])
        elif kind == "flat":
            start = int(rng.integers(0, max(1, n - int(0.5 * sfreq))))
            width = int(0.2 * sfreq)
            epoch[start : start + width] = 0.0
        else:
            t = np.arange(n) / sfreq
            epoch += 25.0 * UV * np.sin(2 * np.pi * 0.2 * t + rng.uniform(0, np.pi))
    counts["artifact"] = 1 if artifact_kind else 0
    return epoch, counts


def generate_recording(
    subject_id: str,
    recording_id: str,
    n_epochs: int,
    sfreq: float = 100.0,
    epoch_seconds: float = 30.0,
    seed: int = 0,
    effect_strength: float = 1.0,
    channel_name: str = "EEG Fpz-Cz",
    include_n3: bool = True,
) -> Recording:
    """Generate a complete synthetic recording with per-epoch stage annotations."""
    rng = np.random.default_rng(seed)
    subject_scale = float(rng.uniform(0.8, 1.25))
    subject_gain = {
        band: float(rng.normal(0.0, 0.15)) for band in ("delta", "theta", "alpha", "sigma", "beta", "beta_high")
    }
    subject_gain["pink"] = float(rng.normal(0.0, 0.08))

    stages = generate_stage_sequence(n_epochs, rng, n3_allowed=include_n3)
    epochs: list[np.ndarray] = []
    event_totals = {"spindle": 0, "kcomplex": 0, "slow_wave": 0}
    for stage in stages:
        epoch, counts = generate_epoch(
            stage,
            sfreq=sfreq,
            epoch_seconds=epoch_seconds,
            rng=rng,
            effect_strength=effect_strength,
            subject_scale=subject_scale,
            subject_gain=subject_gain,
        )
        epochs.append(epoch)
        for key in event_totals:
            event_totals[key] += counts[key]

    signal = np.concatenate(epochs) if epochs else np.zeros(0)
    annotations = [
        StageAnnotation(
            onset=index * epoch_seconds,
            duration=epoch_seconds,
            stage=stage,
            description=f"synthetic:{stage}",
        )
        for index, stage in enumerate(stages)
    ]
    metadata: dict[str, Any] = {
        "generator": "synthetic_psg_v1",
        "effect_strength": effect_strength,
        "subject_scale": subject_scale,
        "subject_gain": {k: round(v, 5) for k, v in subject_gain.items()},
        "event_totals": event_totals,
        "stage_sequence": stages,
        "seed": seed,
    }
    return Recording(
        signal=signal,
        sfreq=sfreq,
        ch_name=channel_name,
        annotations=annotations,
        subject_id=subject_id,
        recording_id=recording_id,
        data_origin="synthetic",
        source_file=None,
        channel_candidates=[channel_name, "EEG Pz-Oz"],
        metadata=metadata,
    )


def generate_corpus(
    n_subjects: int = 8,
    epochs_per_subject: int = 120,
    sfreq: float = 100.0,
    epoch_seconds: float = 30.0,
    seed: int = 20240517,
    effect_strength: float = 1.0,
    include_n3: bool = True,
    channel_name: str = "EEG Fpz-Cz",
) -> list[Recording]:
    """Generate a deterministic multi-subject synthetic corpus."""
    recordings: list[Recording] = []
    for index in range(n_subjects):
        subject_seed = seed + 1000 * (index + 1)
        recordings.append(
            generate_recording(
                subject_id=f"SYN{index:02d}",
                recording_id="R1",
                n_epochs=epochs_per_subject,
                sfreq=sfreq,
                epoch_seconds=epoch_seconds,
                seed=subject_seed,
                effect_strength=effect_strength,
                channel_name=channel_name,
                include_n3=include_n3,
            )
        )
    return recordings


def clone_with(recording: Recording, **changes: Any) -> Recording:
    """Return a shallow-modified copy (used by validation experiments)."""
    return replace(recording, **changes)
