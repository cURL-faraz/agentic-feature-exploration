"""Deterministic synthetic single-channel sleep EEG.

Purpose
-------
The scientific pipeline must be runnable and testable without network access or
a clinical dataset.  This module generates surrogate 30-second EEG epochs whose
*spectral and event structure is specified explicitly* per sleep stage.

**Scientific status: surrogate data.**  Stage differences below are imposed by
construction, so results obtained on this data validate the *machinery*
(extraction, statistics, leakage control, reporting) and can never be presented
as evidence about real sleep EEG.  Every artifact produced from it is tagged
``data_origin: synthetic``.

Signal model
------------
``x(t) = a_s * pink(t)``+
``sum_b g_{s,b} * band_b(t)`` + events, where

* ``pink`` is 1/f^beta noise (beta = 1.4) generated by spectral shaping of white
  noise -- a standard first-order approximation of the EEG background spectrum;
* ``g_{s,b}`` are stage- and band-specific gains (see :data:`STAGE_PROFILES`);
* events are spindle bursts (11-16 Hz, Gaussian envelope), K-complexes
  (biphasic slow deflection) and slow waves (0.5-2 Hz), inserted at
  stage-specific rates.
"""

