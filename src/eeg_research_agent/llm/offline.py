"""Deterministic, template-based "LLM" used when no provider is reachable.

The offline provider exists so that the whole agentic workflow is *executable
without network access or credentials*.  It never invents content: every
sentence it emits is rendered from the structured payload that the calling node
already computed with deterministic code, and every reply carries
``metadata["generated_by"] = "offline-template"`` so a reader can tell prose
generated by a model from prose assembled from saved results.

It implements the same :class:`~.provider.LLMProvider` protocol as the networked
providers, so ``LLMClient`` can use it as a fallback without a special case.
"""

from __future__ import annotations

import json
from typing import Any, Callable

from .provider import LLMReply, LLMRequest

__all__ = ["OfflineProvider", "TASKS"]


def _bullet(items: Any, indent: str = "  ") -> str:
    if isinstance(items, dict):
        items = list(items.items())
        return "\n".join(f"{indent}- {key}: {value}" for key, value in items)
    if isinstance(items, (list, tuple)):
        return "\n".join(f"{indent}- {item}" for item in items)
    return f"{indent}- {items}"


def _fmt(value: Any) -> str:
    if isinstance(value, float):
        return f"{value:.4g}"
    if isinstance(value, (dict, list, tuple)):
        return json.dumps(value, default=str)
    return str(value)


def _t_dataset_summary(payload: dict[str, Any]) -> str:
    summary = payload.get("dataset_summary") or {}
    lines = [
        f"Dataset: {summary.get('dataset', 'unknown')} (origin: {summary.get('data_origin', 'unknown')}).",
        f"Selected derivation: {_fmt(summary.get('selected_channel'))} at "
        f"{_fmt(summary.get('sampling_frequency'))} Hz, "
        f"{_fmt(summary.get('epoch_duration'))} s epochs.",
        f"Subjects: {_fmt(summary.get('subject_count'))}; epochs: {_fmt(summary.get('epoch_count'))}.",
        "Class distribution:",
        _bullet({k: v for k, v in (summary.get("class_distribution") or {}).items() if v}),
    ]
    quality = summary.get("quality_report") or {}
    if quality:
        lines.append("Quality control:")
        lines.append(
            _bullet(
                {
                    key: _fmt(quality[key])
                    for key in ("epochs_total", "epochs_excluded", "epoch_exclusion_fraction")
                    if key in quality
                }
            )
        )
    if str(summary.get("data_origin", "")).startswith("synthetic"):
        lines.append(
            "IMPORTANT: this corpus is synthetic. Nothing here supports a claim about human sleep."
        )
    return "\n".join(lines)


def _t_search_topics(payload: dict[str, Any]) -> str:
    queries = payload.get("queries") or []
    if not queries:
        return "No search plan was supplied."
    lines = [f"Prioritised search plan ({len(queries)} queries):"]
    for index, entry in enumerate(queries, start=1):
        text = entry.get("query") if isinstance(entry, dict) else entry
        topic = entry.get("topic", "") if isinstance(entry, dict) else ""
        lines.append(f"  {index}. {text}" + (f"  [topic: {topic}]" if topic else ""))
    return "\n".join(lines)


def _t_feature_hypotheses(payload: dict[str, Any]) -> str:
    candidates = payload.get("candidates") or []
    selected = payload.get("selected") or [c.get("feature_id") for c in candidates]
    lines = [
        f"Candidate feature specifications generated deterministically: {len(candidates)}.",
        f"Selected for this run: {len(selected)}.",
    ]
    for entry in candidates[:40]:
        lines.append(
            f"  - {entry.get('feature_id')} [{entry.get('category', 'n/a')}] "
            f"params={_fmt(entry.get('parameters', {}))}"
        )
    if payload.get("notes"):
        lines.append("Notes: " + _fmt(payload["notes"]))
    return json.dumps(
        {
            "selected": selected,
            "n_candidates": len(candidates),
            "rationale": (
                "offline provider: the deterministic planner selected the candidates; "
                "no model reasoning was applied."
            ),
        },
        indent=2,
    )


def _t_interpretation(payload: dict[str, Any]) -> str:
    findings = payload.get("findings") or []
    lines = [str(payload.get("question", "Interpretation of saved results."))]
    for finding in findings[:20]:
        if isinstance(finding, dict):
            lines.append(
                "  - "
                + ", ".join(f"{key}={_fmt(value)}" for key, value in finding.items())
            )
        else:
            lines.append(f"  - {finding}")
    lines.append(
        "Statement of scope: every number above is a saved computation output. "
        "Association is not causation, and predictive improvement is not biological significance."
    )
    return "\n".join(lines)


def _t_report_section(payload: dict[str, Any]) -> str:
    title = str(payload.get("title", "Section"))
    body = payload.get("body_markdown")
    if body:
        return f"## {title}\n\n{body}"
    sections = payload.get("data") or {}
    lines = [f"## {title}", ""]
    for key, value in sections.items():
        lines.append(f"### {key.replace('_', ' ').title()}")
        lines.append(_bullet(value) if isinstance(value, (dict, list, tuple)) else _fmt(value))
        lines.append("")
    return "\n".join(lines).strip()


def _t_generic(payload: dict[str, Any]) -> str:
    return (
        "Offline provider: no networked LLM is configured, so this response is a "
        "deterministic rendering of the supplied payload rather than model reasoning.\n"
        + _fmt(payload)
    )


#: Task name -> deterministic template.
TASKS: dict[str, Callable[[dict[str, Any]], str]] = {
    "dataset_summary": _t_dataset_summary,
    "search_topics": _t_search_topics,
    "feature_hypotheses": _t_feature_hypotheses,
    "interpretation": _t_interpretation,
    "report_section": _t_report_section,
}


class OfflineProvider:
    """Template renderer exposing the ``LLMProvider`` protocol."""

    name = "offline"
    requires_api_key = False
    network = False
    _MODELS = ("offline-template-v1",)

    def __init__(self, model: str = "offline-template-v1") -> None:
        self.model = model

    def __repr__(self) -> str:  # pragma: no cover - trivial
        return f"OfflineProvider(model={self.model!r})"

    def list_models(self) -> list[str]:
        return list(self._MODELS)

    def complete(self, request: LLMRequest) -> LLMReply:
        payload = request.metadata.get("payload") or {}
        task = str(request.metadata.get("task") or "generic")
        template = TASKS.get(task, _t_generic)
        return LLMReply(
            text=template(payload),
            model=self.model,
            provider=self.name,
            usage={"input_chars": len(request.prompt_text()), "output_chars": 0},
            metadata={
                "task": task,
                "generated_by": "offline-template",
                "reasoning": False,
                "deterministic": True,
            },
        )
